
CREATE TABLE Dist_Item (
    Dno     VARCHAR2(4),
    Item_No VARCHAR2(5),
    Qty     NUMBER(6) NOT NULL CHECK (Qty > 0),
    Order_Date DATE,
    PRIMARY KEY (Dno, Item_No),
    FOREIGN KEY (Dno) REFERENCES Distributor(Dno),
    FOREIGN KEY (Item_No) REFERENCES Item(Item_No)
);


